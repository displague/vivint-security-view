#!/usr/bin/env node
// Writes the lan overlay's Secrets to a local, git-ignored YAML file:
//   vivint-panel   settings.json with the panel RTSP URLs (the long-lived panel credential)
//   vivint-app     STREAM_TOKEN, random, kept across re-runs
//   vivint-signin  sign-in allowlist and session key; the Google client is added when one exists
// Prints a summary only, never secret values. Apply with: kubectl apply -f <output>
//
// Usage:
//   VIVINT_SIGNIN_ALLOWED_EMAILS="a@x.com,b@y.com" node scripts/make_lan_secrets.js \
//     [--settings settings.json] [--out k8s/overlays/lan/secrets.local.yaml] [--namespace vivint]
// Optional env: GOOGLE_SIGNIN_CLIENT_ID, GOOGLE_SIGNIN_CLIENT_SECRET.

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

function arg(name, fallback) {
  const index = process.argv.indexOf(`--${name}`);
  return index > 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

const root = path.resolve(__dirname, "..");
const settingsPath = path.resolve(arg("settings", path.join(root, "settings.json")));
const outPath = path.resolve(arg("out", path.join(root, "k8s/overlays/lan/secrets.local.yaml")));
const namespace = arg("namespace", "vivint");

function previousValue(key) {
  if (!fs.existsSync(outPath)) {
    return null;
  }
  const match = fs.readFileSync(outPath, "utf8").match(new RegExp(`^\\s+${key}: "([^"]+)"$`, "m"));
  return match ? match[1] : null;
}

function quote(value) {
  return JSON.stringify(String(value));
}

function secret(name, entries) {
  const lines = [
    "apiVersion: v1",
    "kind: Secret",
    "metadata:",
    `  name: ${name}`,
    `  namespace: ${namespace}`,
    "type: Opaque",
    "stringData:"
  ];
  for (const [key, value] of entries) {
    if (key.endsWith(".json")) {
      lines.push(`  ${key}: |`);
      for (const line of value.split("\n")) {
        lines.push(`    ${line}`);
      }
    } else {
      lines.push(`  ${key}: ${quote(value)}`);
    }
  }
  return lines.join("\n");
}

function main() {
  if (!fs.existsSync(settingsPath)) {
    throw new Error(`No settings.json at ${settingsPath}`);
  }
  const settings = JSON.parse(fs.readFileSync(settingsPath, "utf8"));
  const cameras = Array.isArray(settings.cameras) ? settings.cameras : [];
  if (cameras.length === 0) {
    throw new Error("settings.json has no cameras");
  }

  // Re-runs keep earlier values unless new ones are passed in.
  const allowedEmails = String(
    process.env.VIVINT_SIGNIN_ALLOWED_EMAILS || previousValue("GOOGLE_SIGNIN_ALLOWED_EMAILS") || ""
  )
    .split(/[\s,]+/)
    .map((email) => email.trim().toLowerCase())
    .filter(Boolean);
  for (const email of allowedEmails) {
    if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) {
      throw new Error("VIVINT_SIGNIN_ALLOWED_EMAILS has an entry that isn't an email address");
    }
  }

  const previousToken = previousValue("STREAM_TOKEN");
  const streamToken = previousToken || crypto.randomBytes(24).toString("base64url");
  const sessionSecret = previousValue("SESSION_SECRET") || crypto.randomBytes(48).toString("base64url");

  const signin = [["SESSION_SECRET", sessionSecret]];
  if (allowedEmails.length > 0) {
    signin.push(["GOOGLE_SIGNIN_ALLOWED_EMAILS", allowedEmails.join(",")]);
  }
  const clientId = process.env.GOOGLE_SIGNIN_CLIENT_ID || previousValue("GOOGLE_SIGNIN_CLIENT_ID");
  const clientSecret =
    process.env.GOOGLE_SIGNIN_CLIENT_SECRET || previousValue("GOOGLE_SIGNIN_CLIENT_SECRET");
  if (clientId) {
    signin.push(["GOOGLE_SIGNIN_CLIENT_ID", clientId]);
  }
  if (clientSecret) {
    signin.push(["GOOGLE_SIGNIN_CLIENT_SECRET", clientSecret]);
  }

  const documents = [
    "# Generated by scripts/make_lan_secrets.js. Holds credentials: never commit or paste this file.",
    secret("vivint-panel", [["settings.json", JSON.stringify({ cameras }, null, 2)]]),
    secret("vivint-app", [["STREAM_TOKEN", streamToken]]),
    secret("vivint-signin", signin)
  ];
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, `${documents.join("\n---\n")}\n`, { encoding: "utf8", mode: 0o600 });

  process.stdout.write(
    `${JSON.stringify(
      {
        wrote: path.relative(root, outPath),
        namespace,
        cameras: cameras.map((camera) => camera.camera_id ?? camera.id),
        streamToken: previousToken ? "kept" : "generated",
        signInAllowlistEntries: allowedEmails.length,
        googleClientConfigured: Boolean(clientId && clientSecret)
      },
      null,
      2
    )}\n`
  );
}

try {
  main();
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exit(1);
}
